export async function generateSmartConversationalReply(
  userQuery: string,
  _history: any[] = []
): Promise<string> {
  const q = userQuery.toLowerCase().trim();

  // 1. Check for Surah specific question (e.g. سورة الملك، سورة الكهف، سورة يوسف...)
  const surahMatch = q.match(/سورة\s+([\u0621-\u064A]+)/);
  if (surahMatch) {
    const surahName = surahMatch[1];
    return `### 📖 تدبر وهدايات سورة ${surahName}

سورة ${surahName} من السور العظيمة في كتاب الله ولها أسرار بيانية وإيمانية جليلة:

1. **المقصد الأساسي للسورة**:
   ترسيخ التوحيد، وبيان دلائل قدرة الله في الأنفس والآفاق، وتذكير القلوب باليوم الآخر.

2. **اللطيفة التدبرية**:
   التأمل في فواتح السورة وخواتيمها يكشف عن ربط بديع بين عظمة الخالق وحاجة العبد للاستسلام له.

3. **العمل بالسورة**:
   - قراءتها بتؤدة واستحضار معاني كلماتها.
   - تطبيق أوامرها ومحاذيرها في يومك.

💡 يمكنك فتح **سورة ${surahName}** مباشرة في مصحف المدينة لقراءة التفسير الميسر كاملاً آية بآية، أو الانتقال لحلقة التسميع لاختبار حفظك الغيبي لها.`;
  }

  // 2. Check Topic Knowledge Base
  for (const item of KNOWLEDGE_BASE) {
    const matched = item.keywords.some(k => q.includes(k));
    if (matched) {
      const v = item.verses[0];
      return `### 🌟 ${item.title}

${v.text}
*(سورة ${v.surah} - الآية ${v.ayah})*

**📖 التفسير الميسر (مصحف المدينة النبوية):**
${v.tafsir}

**💡 اللطائف والفوائد التدبرية:**
${item.reflections.map(r => `• ${r}`).join('\n')}

**🎯 كيف نعمل بالآية اليوم؟**
${item.actionStep}`;
    }
  }

  // 3. Fallback Dynamic Conversational Response for General Questions
  return `### 💡 التوجيه والتدبر القرآني

أهلاً بك يا رفيق القرآن الكريم. سؤالك المبارك: *" ${userQuery} "* يحمل في طياته حرصاً طيباً على الفهم والتدبر.

**📖 المنهج القرآني المعتمد (مصحف المدينة النبوية):**
1. القرآن الكريم منهج حياة متكامل؛ ما من مسألة يسأل عنها العبد إلا وفي كتاب الله أصلها ونورها وهدايتها: *(وَنَزَّلْنَا عَلَيْكَ الْكِتَابَ تِبْيَانًا لِّكُلِّ شَيْءٍ وَهُدًى وَرَحْمَةً)*.
2. تدبر الآيات يبدأ بحسن الاستماع والإنصات، ثم فهم المعنى من التفسير الميسر، ثم استخراج الدرس الإيماني، ثم العمل الفوري بما علمت.

**🎯 خيارات سريعة لمساعدتك الآن:**
• اضغط على **"المصحف"** لتصفح السور وتفسير أي آية تختارها.
• اضغط على **"حلقة التسميع"** لمراجعة حفظك والتسميع الغيبي مع الشيخ المعلم.
• اضغط على **"معمل التجويد"** للتدريب الصوتي على نطق الحروف وأحكام التلاوة.

ما هي السورة أو الآية التي تحب أن نتدبرها سوياً الآن؟`;
}
